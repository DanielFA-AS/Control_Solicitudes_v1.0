CREATE TABLE HISTORIAL_TRAZABILIDAD
(
    Id INT IDENTITY(1,1) PRIMARY KEY,
    FK_Solicitud INT NOT NULL,
    FechaHora NVARCHAR(50) NOT NULL,
    FK_Accion INT NOT NULL,
    Detalle NVARCHAR(250) NOT NULL,
    ComResolu NVARCHAR(100) NOT NULL

    FOREIGN KEY (FK_Solicitud) REFERENCES SOLICITUD(Id),
    FOREIGN KEY (FK_Accion) REFERENCES ACCIONES_TRAZABILIDAD(Id),
);