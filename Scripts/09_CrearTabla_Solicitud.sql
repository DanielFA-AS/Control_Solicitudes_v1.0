CREATE TABLE SOLICITUD
(
    Id INT IDENTITY(1,1) PRIMARY KEY,
    FK_Solicitante INT NOT NULL,
    FK_Tipo INT NOT NULL,
    Titulo INT NOT NULL,
    FeCreacion DATETIME2 NOT NULL,
    Descripcion NVARCHAR(150) NOT NULL,
    FK_Prioridad INT NOT NULL,
    FK_Responsable INT NOT NULL,
    FK_Estado INT NOT NULL

    FOREIGN KEY (FK_Solicitante) REFERENCES USUARIOS(Id),
    FOREIGN KEY (FK_Tipo) REFERENCES TIPO_SOLICITUD(Id),
    FOREIGN KEY (FK_Prioridad) REFERENCES PRIORIDAD(Id),
    FOREIGN KEY (FK_Responsable) REFERENCES DESARROLLADORES(Id),
    FOREIGN KEY (FK_Estado) REFERENCES ESTADO(Id)
);